"""Edit the original decks of old chapters 1-9 in place for the 18-chapter book.

- chapter numbers/ordinals, file names and unified terminology in all slide text (paragraph level)
- replaced sections (trimmed topics) and the merged closing section get slides generated by slidegen
  inside the original deck, in the original section order; removed slides are dropped
- page numbers are rewritten
Input ../src_slides/ChNN_Slides.pptx -> ../out/slides/ChMM_Slides.pptx
"""
import importlib, os, re, sys
from pptx import Presentation
from pptx.oxml.ns import qn

GEN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, GEN); sys.path.insert(0, os.path.join(GEN, "content")); sys.path.insert(0, os.path.join(GEN, "edits"))
from renumber import remap, MAP
from textterms import unify
from slidegen import Deck, compress_background

def _load_meta():
    """R pairs from fix_meta_after_trim.py (keyed by OLD chapter number) without running that script."""
    src = open(os.path.join(GEN, "edits", "fix_meta_after_trim.py"), encoding="utf-8").read()
    ns = {"os": os}
    exec(src[src.index("R = {"):src.index("import importlib, pprint")], ns)
    return ns["R"]


META = _load_meta()

# slides whose content changed although the section is kept (regenerated, original slide dropped)
OVERRIDES = {
    1: {25: dict(axis=3, t="بنية المقرر: الفصول والخطوات", en="Course Architecture",
                 lead="ثمانية عشر فصلا في أربعة أجزاء، يخدم كل منها خطوة أو أكثر من الخطوات الست.",
                 blk=("table", ["الجزء", "الفصول", "ما يغطيه"], [
                     ["صياغة القرار وتقييم شواهده", "1–5", "المفهوم، والصياغة، والشواهد، والاستدلال الإحصائي والسببي"],
                     ["مقارنة البدائل تحت المخاطر", "6–10", "التنبؤ، وتقييم النماذج، وعدم اليقين، والتحسين، والمعايير المتعددة"],
                     ["إيصال القرار وتنفيذه", "11–14", "التحيّزات، والذكاء الاصطناعي، وسرد القصة، والتنفيذ والحوكمة"],
                     ["القرار في المنظمة والمجتمع", "15–18", "الأخلاقيات، والمنظمة، والتطبيقات السعودية، والقرار المتكامل"],
                 ], [2.4, 0.9, 4.6]),
                 take="أربعة أجزاء: صياغة القرار وشواهده (1–5)، والبدائل تحت المخاطر (6–10)، والإيصال والتنفيذ (11–14)، والمنظمة والمجتمع (15–18).")},
}

SRC = os.path.join(GEN, "..", "src_slides")
DST = os.path.join(GEN, "..", "out", "slides")
E = 914400


def transform_factory(old, new):
    pairs = META.get(old, [])
    def f(s):
        for a, b in pairs:
            s = s.replace(a, b)
        s = remap(s)
        s = re.sub(r"Ch0%d_" % old, "Ch%02d_" % new, s)
        return unify(s)
    return f


def fix_paragraphs(element, f):
    n = 0
    for p in element.iter(qn("a:p")):
        runs = [r for r in p.iter(qn("a:r"))]
        ts = [r.find(qn("a:t")) for r in runs]
        ts = [t for t in ts if t is not None]
        if not ts:
            continue
        full = "".join(t.text or "" for t in ts)
        new = f(full)
        if new == full:
            continue
        per = [f(t.text or "") for t in ts]
        if "".join(per) == new:
            for t, v in zip(ts, per):
                t.text = v
        else:
            ts[0].text = new
            for t in ts[1:]:
                t.text = ""
        n += 1
    return n


class InPlaceDeck(Deck):
    def __init__(self, ch, prs, layout):
        self.ch = ch
        self.prs = prs
        self.layout_light = layout
        self.layout_dark = layout
        self.n = 0


def slide_title(slide):
    for sh in slide.shapes:
        if sh.has_text_frame and abs(sh.top / E - 0.72) < 0.03:
            return sh.text_frame.text.strip()
    return ""


def renumber_pages(prs):
    k = 0
    for i, s in enumerate(prs.slides, 1):
        for sh in s.shapes:
            if sh.has_text_frame and abs(sh.left / E - 0.40) < 0.02 and abs(sh.top / E - 5.28) < 0.02 \
                    and re.fullmatch(r"\d+", sh.text_frame.text.strip() or "x"):
                r = sh.text_frame.paragraphs[0].runs
                if r:
                    r[0].text = str(i)
                    for x in r[1:]:
                        x.text = ""
                k += 1
    return k


def process(old):
    new = MAP[old]
    ch = importlib.import_module(f"ch{new:02d}").CH
    prs = Presentation(os.path.join(SRC, f"Ch{old:02d}_Slides.pptx"))
    f = transform_factory(old, new)
    changed = 0
    for part in [*prs.slide_masters, *prs.slide_layouts]:
        changed += fix_paragraphs(part.element, f)
    for s in prs.slides:
        changed += fix_paragraphs(s.element, f)
        if s.has_notes_slide:
            changed += fix_paragraphs(s.notes_slide.element, f)
    slides = list(prs.slides)
    sld_ids = list(prs.slides._sldIdLst)
    n_orig_secs = len(slides) - 6
    orig_secs = list(range(3, 3 + n_orig_secs))
    layout = slides[3].slide_layout
    deck = InPlaceDeck(ch, prs, layout)
    order, used, ptr = [0, 1, 2], set(), 0
    for k, sec in enumerate(ch["sections"]):
        if k in OVERRIDES.get(old, {}):
            deck.section(OVERRIDES[old][k])
            order.append(len(prs.slides) - 1)
            ptr += 1
        elif sec.get("new_slide"):
            s = deck.section(sec)
            new_idx = len(prs.slides) - 1
            order.append(new_idx)
            ptr += 2 if sec.get("merged_from") else 1
        else:
            idx = orig_secs[ptr]
            t = slide_title(slides[idx])
            if t != sec["t"]:
                print(f"  [{old}->{new}] title differs: slide «{t}» vs content «{sec['t']}»")
            order.append(idx)
            ptr += 1
    assert ptr == n_orig_secs, (old, ptr, n_orig_secs)
    order += [3 + n_orig_secs, 4 + n_orig_secs, 5 + n_orig_secs]
    all_ids = list(prs.slides._sldIdLst)
    keep = [all_ids[i] for i in order]
    lst = prs.slides._sldIdLst
    for sid in list(lst):
        lst.remove(sid)
        if sid not in keep:
            prs.part.drop_rel(sid.rId)
    for sid in keep:
        lst.append(sid)
    pages = renumber_pages(prs)
    os.makedirs(DST, exist_ok=True)
    out = os.path.join(DST, f"Ch{new:02d}_Slides.pptx")
    prs.save(out)
    compress_background(out)
    print(f"Ch{old:02d} -> Ch{new:02d}: {len(prs.slides)} slides, {changed} paragraphs edited, {pages} page numbers")


if __name__ == "__main__":
    for old in range(1, 10):
        process(old)
